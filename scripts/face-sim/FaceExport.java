import com.isaigu.gymapp.ai.AiModel;
import com.isaigu.gymapp.ai.AutoCatalog;
import com.isaigu.gymapp.ai.AutoModel;
import com.isaigu.gymapp.ai.AutoPlanner;
import com.isaigu.gymapp.wearable.bluetens.BluetensPrograms;
import com.isaigu.gymapp.wearable.face.FaceArt;
import com.isaigu.gymapp.wearable.face.FaceProgram;

import java.io.FileOutputStream;
import java.util.Locale;

/**
 * The face procedures as one data file (docs/xems-face.md §10) — the single source the XBody panel (C++) and any other
 * device read instead of re-typing them: names and texts, the XEMS sites (sockets F1–F10), the Bluetens devices and
 * their files, the plan step by step exactly as the automatic mode builds it (after its limits), and the picture's
 * geometry (sites, pads, keep-out zones).
 * usage: java FaceExport <out.json>   (scripts/face-sim/export.sh writes branding/face/procedures.json)
 */
public class FaceExport {
    static final StringBuilder o = new StringBuilder();
    static int depth;

    public static void main(String[] args) throws Exception {
        o.append("{\n");
        depth = 1;
        field("format", "xems-face/1");
        field("source", "generated by scripts/face-sim/export.sh from FaceProgram, AutoCatalog/AutoPlanner, FaceArt, "
                + "BluetensPrograms — do not edit by hand");
        field("reference_client", "female, 45 y, 65 kg, 168 cm, medium fitness, 10 sessions (after adaptation)");
        picture();
        limits();
        sites();
        keepOut();
        procedures();
        o.setLength(o.length() - 2);
        o.append("\n}\n");
        FileOutputStream f = new FileOutputStream(args[0]);
        f.write(o.toString().getBytes("UTF-8"));
        f.close();
    }

    // ---------------------------------------------------------------- sections

    static void picture() {
        open("picture", false);
        field("file", "face.webp");
        field("w", FaceArt.W);
        field("h", FaceArt.H);
        field("px_per_cm", FaceArt.CM);
        field("mirror_axis_x", FaceArt.AXIS);
        field("left_is_viewer_right", true);
        close();
    }

    static void limits() {
        open("limits", false);
        field("motor_hz_min", AutoCatalog.FACE_HZ_MIN);
        field("motor_pw_us", AutoCatalog.FACE_PW);
        field("forehead_pw_us", AutoCatalog.FACE_RELAX_PW);
        field("jaw_pw_us", AutoCatalog.FACE_JAW_PW);
        field("chin_pw_us", AutoCatalog.FACE_CHIN_PW);
        field("recovery_s", AutoCatalog.FACE_RECOVERY_S);
        field("connector_pad_mm", new int[] {12, 16});
        field("bluetens_pad_mm", new int[] {16, 19});
        field("bluetens_devices_max", 3);
        field("plus_is_one_step_per_tap", true);
        close();
    }

    static void sites() {
        o.append(ind()).append("\"sites\": [\n");
        depth++;
        for (int s = 0; s < FaceArt.SITES; s++) {
            o.append(ind()).append("{");
            o.append("\"id\": ").append(s).append(", \"socket\": \"F").append(s + 1).append("\", \"suit_channel\": ").append(s);
            o.append(", \"name_bg\": ").append(q(FaceProgram.siteName(s, true)));
            o.append(", \"name_en\": ").append(q(FaceProgram.siteName(s, false)));
            float[][] p = FaceArt.pads(s);
            o.append(", \"pads\": [").append(pt(p[0])).append(", ").append(pt(p[1])).append("]");
            o.append(", \"pad_angle_deg\": ").append(num(FaceArt.padAngle(s)));
            o.append("}").append(s < FaceArt.SITES - 1 ? "," : "").append("\n");
        }
        depth--;
        o.append(ind()).append("],\n");
    }

    static void keepOut() {
        open("keep_out", false);
        o.append(ind()).append("\"eye\": {\"centre\": ").append(pt(FaceArt.EYE)).append(", \"rx\": ").append(num(FaceArt.EYE_RX))
                .append(", \"ry\": ").append(num(FaceArt.EYE_RY)).append(", \"mirrored\": true},\n");
        o.append(ind()).append("\"eye_corner\": ").append(pt(FaceArt.CANTHUS)).append(",\n");
        o.append(ind()).append("\"nerve_trunk\": ").append(pt(FaceArt.TRUNK)).append(",\n");
        o.append(ind()).append("\"neck_side\": ").append(pt(FaceArt.NECK)).append(",\n");
        o.append(ind()).append("\"mouth_corner\": ").append(pt(FaceArt.MOUTH)).append(",\n");
        close();
    }

    static void procedures() {
        o.append(ind()).append("\"procedures\": [\n");
        depth++;
        int[] ids = FaceProgram.XEMS;
        for (int k = 0; k < ids.length; k++) {
            procedure(FaceProgram.get(ids[k]));
            o.setLength(o.length() - 2);
            o.append(k < ids.length - 1 ? ",\n" : "\n");
        }
        depth--;
        o.append(ind()).append("],\n");
    }

    static void procedure(FaceProgram p) {
        o.append(ind()).append("{\n");
        depth++;
        String auto = autoId(p.id);
        field("id", p.id);
        field("auto_id", auto);
        field("name_bg", p.nameBg);
        field("name_en", p.nameEn);
        field("tag_bg", p.tagBg);
        field("tag_en", p.tagEn);
        field("muscle_bg", p.muscleBg);
        field("muscle_en", p.muscleEn);
        field("latin", p.latin);
        field("sensory", p.sensory);
        field("evidence", p.evidence);
        field("tint", String.format("#%06X", p.tint & 0xFFFFFF));
        field("glyph", p.glyph);
        field("rhythm_bg", p.rhythm(true));
        field("course_bg", p.course(true));
        open("course", false);
        field("weeks", p.weeks);
        field("planned_sessions", p.planned);
        field("gap_early_days", p.gapEarly);
        field("gap_later_days", p.gapLater);
        close();
        field("how_bg", p.how(true));
        field("how_en", p.how(false));
        field("place_xems_bg", p.place(true, true));
        field("place_bluetens_bg", p.place(true, false));
        field("strength_goal_bg", p.strengthGoal(true));
        field("strength_goal_en", p.strengthGoal(false));
        field("xems_sites", p.xemsSites());
        int[] bs = p.bluetensSites();
        field("bluetens_sites", bs);
        String[] files = new String[bs.length];
        for (int d = 0; d < bs.length; d++) {
            files[d] = BluetensPrograms.fileName(BluetensPrograms.faceFile(p.id, bs[d], bs.length), 10).substring(1, 4);
        }
        field("bluetens_files", files);
        plan(auto);
        o.setLength(o.length() - 2);
        o.append("\n");
        depth--;
        o.append(ind()).append("},\n");
    }

    /** The plan exactly as the automatic mode builds it (after AutoLimits) for the reference client. */
    static void plan(String autoId) {
        AutoModel.Input in = new AutoModel.Input();
        in.sex = AiModel.Sex.FEMALE;
        in.age = 45;
        in.weightKg = 65;
        in.heightCm = 168;
        in.fitness = AiModel.Fitness.MID;
        in.sessions = 10;
        in.hoursSinceActive = -1;
        in.goal = AutoModel.Goal.TONE;
        in.kind = AutoModel.Kind.PASSIVE;
        in.programId = autoId;
        AutoModel.Plan plan = AutoPlanner.build(in, 70);
        open("plan", false);
        field("active_s", plan.activeS);
        field("recovery_s", plan.recoveryS);
        field("total_s", plan.totalS);
        field("zones", plan.zones);
        o.append(ind()).append("\"phases\": [\n");
        depth++;
        for (int i = 0; i < plan.phases.size(); i++) {
            AutoModel.Phase ph = plan.phases.get(i);
            o.append(ind()).append("{");
            o.append("\"id\": ").append(q(ph.id)).append(", \"name_bg\": ").append(q(ph.nameBg)).append(", \"duration_s\": ")
                    .append(ph.durationS).append(", \"cooldown\": ").append(ph.isCooldown()).append(", \"wave\": ").append(ph.wave)
                    .append(", \"phi\": [").append(num(ph.phiStart)).append(", ").append(num(ph.phiEnd)).append("]")
                    .append(", \"env\": [").append(num(ph.envStart)).append(", ").append(num(ph.envEnd)).append("]")
                    .append(", \"hint_bg\": ").append(q(ph.hintBg)).append(",\n");
            depth++;
            o.append(ind()).append("\"steps\": [\n");
            depth++;
            for (int k = 0; k < ph.steps.size(); k++) {
                AutoModel.Step s = ph.steps.get(k);
                o.append(ind()).append("{\"hz\": ").append(s.hz).append(", \"pw_us\": ").append(s.pwUs).append(", \"on_s\": ")
                        .append(s.onS).append(", \"off_s\": ").append(s.offS).append(", \"ramp_up_ms\": ").append(s.rampUpMs)
                        .append(", \"ramp_down_ms\": ").append(s.rampDownMs).append(", \"sigma\": ").append(num(s.sigma))
                        .append(", \"zones\": ").append(s.zones == null ? "null" : arr(s.zones)).append("}")
                        .append(k < ph.steps.size() - 1 ? "," : "").append("\n");
            }
            depth--;
            o.append(ind()).append("]\n");
            depth--;
            o.append(ind()).append("}").append(i < plan.phases.size() - 1 ? "," : "").append("\n");
        }
        depth--;
        o.append(ind()).append("]\n");
        depth--;
        o.append(ind()).append("},\n");
    }

    static String autoId(int program) {
        switch (program) {
            case FaceProgram.FIRM: return AutoCatalog.FACE_TONE;
            case FaceProgram.OVAL: return AutoCatalog.FACE_OVAL;
            case FaceProgram.DRAIN: return AutoCatalog.FACE_DRAIN;
            case FaceProgram.RELAX: return AutoCatalog.FACE_RELAX;
            case FaceProgram.CALM: return AutoCatalog.FACE_CALM;
            case FaceProgram.JAW_RELAX: return AutoCatalog.FACE_JAW;
            case FaceProgram.CONTOUR: return AutoCatalog.FACE_CHIN;
            default: return AutoCatalog.FACE;
        }
    }

    // ---------------------------------------------------------------- tiny JSON writer (stable output: the test compares bytes)

    static String ind() {
        StringBuilder b = new StringBuilder();
        for (int i = 0; i < depth; i++) {
            b.append("  ");
        }
        return b.toString();
    }

    static void open(String name, boolean array) {
        o.append(ind()).append(q(name)).append(": ").append(array ? "[" : "{").append("\n");
        depth++;
    }

    static void close() {
        o.setLength(o.length() - 2);
        o.append("\n");
        depth--;
        o.append(ind()).append("},\n");
    }

    static void field(String k, String v) {
        o.append(ind()).append(q(k)).append(": ").append(q(v)).append(",\n");
    }

    static void field(String k, int v) {
        o.append(ind()).append(q(k)).append(": ").append(v).append(",\n");
    }

    static void field(String k, float v) {
        o.append(ind()).append(q(k)).append(": ").append(num(v)).append(",\n");
    }

    static void field(String k, boolean v) {
        o.append(ind()).append(q(k)).append(": ").append(v).append(",\n");
    }

    static void field(String k, int[] v) {
        o.append(ind()).append(q(k)).append(": ").append(arr(v)).append(",\n");
    }

    static void field(String k, String[] v) {
        StringBuilder b = new StringBuilder("[");
        for (int i = 0; i < v.length; i++) {
            b.append(i > 0 ? ", " : "").append(q(v[i]));
        }
        o.append(ind()).append(q(k)).append(": ").append(b).append("],\n");
    }

    static String arr(int[] v) {
        StringBuilder b = new StringBuilder("[");
        for (int i = 0; i < v.length; i++) {
            b.append(i > 0 ? ", " : "").append(v[i]);
        }
        return b.append("]").toString();
    }

    static String pt(float[] p) {
        return "[" + num(p[0]) + ", " + num(p[1]) + "]";
    }

    static String num(double v) {
        if (v == Math.rint(v)) {
            return String.valueOf((long) v);
        }
        return String.format(Locale.US, "%.2f", v);
    }

    static String q(String s) {
        if (s == null) {
            return "null";
        }
        StringBuilder b = new StringBuilder("\"");
        for (int i = 0; i < s.length(); i++) {
            char c = s.charAt(i);
            switch (c) {
                case '"': b.append("\\\""); break;
                case '\\': b.append("\\\\"); break;
                case '\n': b.append("\\n"); break;
                default:
                    if (c < 0x20) {
                        b.append(String.format("\\u%04x", (int) c));
                    } else {
                        b.append(c);
                    }
            }
        }
        return b.append("\"").toString();
    }
}
