#!/usr/bin/env python3
"""Parity data for vr-workout/test/prior_test.gd: a held-out CMU clip's inputs (2 s at 60 fps) and what the Python
network says (legs_prior.Prior) → test/prior_test_data.gd. The Godot test feeds the same inputs to LegsPrior and
checks the same outputs: the GDScript port is the trained model, not an approximation of it.

  python3 scripts/vr-legs/gen_prior_test.py <clip.npz> <weights.json> <out.gd>
"""
import json, math, sys
import numpy as np
import legs_prior as LP
import legs_eval as LE


class Fake:
    pass


def main(clip, wpath, out):
    net = LP.load(wpath)
    d = dict(np.load(clip))
    pr = LP.Prior(net)
    legs = Fake()
    eye_h = d['eye'][:, 1]
    fl = float(d['floor'])
    stand_ankle = float(np.percentile(eye_h, 95)) - fl
    H = (stand_ankle + 0.039 * (stand_ankle / 0.936)) / 0.936
    legs.stand_h = stand_ankle + 0.039 * H
    legs.ah = 0.039 * H
    legs.floor_y = fl - legs.ah
    legs.use_acc = True
    legs.v = {'l': {'bias': 0.0}, 'r': {'bias': 0.0}}
    rng = np.random.default_rng(3)
    rows = []
    start = 200
    for i in range(start, start + 120):
        U = {sd: d['u_' + sd][i].astype(float) for sd in 'lr'}
        A = {sd: LE.nrm(d['a_' + sd][i].astype(float)) for sd in 'lr'}
        acc = {sd: float(rng.normal(0, 0.3)) for sd in 'lr'}
        legs.acc_now = acc
        legs.hands_now = {sd: d['wrist_' + sd][i].astype(float) for sd in 'lr'} if 'wrist_l' in d else None
        head = d['eye'][i].astype(float)
        f = np.zeros(3)
        for sd in 'lr':
            f += np.cross(A[sd], LE.UP)
        f[1] = 0
        bf = f / np.linalg.norm(f)
        o = pr(legs, U, A, head, bf)
        hn = legs.hands_now or {'l': np.zeros(3), 'r': np.zeros(3)}
        r = [*U['l'], *U['r'], *A['l'], *A['r'], acc['l'], acc['r'], *head, *hn['l'], *hn['r'],
             float(o['ground']['l']), float(o['ground']['r']), *o['thigh']['l'], *o['thigh']['r'], *o['pc']]
        rows.append(r)
    with open(out, 'w') as f:
        f.write('## GENERATED by scripts/vr-legs/gen_prior_test.py — parity data for test/prior_test.gd\n')
        f.write('extends RefCounted\n\n')
        f.write('const S := %.6f\nconst ANKLE_Y := %.6f\n' % (legs.stand_h - legs.ah, legs.floor_y + legs.ah))
        f.write('const ROWS := [\n')
        for r in rows:
            f.write('\t[' + ','.join('%.6g' % x for x in r) + '],\n')
        f.write(']\n')


if __name__ == '__main__':
    main(*sys.argv[1:4])
